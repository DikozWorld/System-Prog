#include <X11/Xlib.h>
#include <X11/Xutil.h>

#include <stdio.h>
#include <stdlib.h>

/*
    ==========================================
    ЛАБА 2
    Простейший графический редактор
    Один цвет
    ==========================================

    Что умеет программа:
    - открывает окно
    - рисует при зажатой ЛКМ
    - рисует линии между точками мыши
    - завершает работу по ESC

    Главная идея:
    Мы постоянно получаем события мыши
    и соединяем точки линиями.
*/

int main() {

    /*
        ==========================================
        ОСНОВНЫЕ ОБЪЕКТЫ XLIB
        ==========================================
    */

    // Подключение к X-серверу
    Display *display;

    // Главное окно программы
    Window window;

    // Универсальная структура событий
    XEvent event;

    // Graphics Context
    // Хранит параметры рисования
    GC gc;

    /*
        ==========================================
        ПЕРЕМЕННЫЕ ДЛЯ РИСОВАНИЯ
        ==========================================
    */

    /*
        drawing:
        0 -> не рисуем
        1 -> ЛКМ зажата, рисуем
    */
    int drawing = 0;

    /*
        Последняя позиция мыши.

        Нужна для рисования линии:
        от старой точки
        до новой точки.
    */
    int last_x = 0;
    int last_y = 0;

    /*
        ==========================================
        ПОДКЛЮЧЕНИЕ К X11
        ==========================================
    */

    display = XOpenDisplay(NULL);

    // Проверяем подключение
    if (display == NULL) {

        printf("Не удалось подключиться к X-серверу\n");

        return 1;
    }

    /*
        ==========================================
        ПОЛУЧАЕМ ЭКРАН
        ==========================================
    */

    int screen = DefaultScreen(display);

    /*
        ==========================================
        СОЗДАЁМ ОКНО
        ==========================================
    */

    window = XCreateSimpleWindow(

        display,

        // Родительское окно
        RootWindow(display, screen),

        // Позиция окна
        100, 100,

        // Размер окна
        800, 600,

        // Толщина рамки
        1,

        // Цвет рамки
        BlackPixel(display, screen),

        // Цвет фона
        WhitePixel(display, screen)
    );

    /*
        ==========================================
        ВЫБИРАЕМ СОБЫТИЯ
        ==========================================

        ExposureMask
            -> перерисовка окна

        ButtonPressMask
            -> нажатие мыши

        ButtonReleaseMask
            -> отпускание мыши

        PointerMotionMask
            -> движение мыши

        KeyPressMask
            -> клавиатура
    */

    XSelectInput(
        display,
        window,

        ExposureMask |
        ButtonPressMask |
        ButtonReleaseMask |
        PointerMotionMask |
        KeyPressMask
    );

    /*
        ==========================================
        НАЗВАНИЕ ОКНА
        ==========================================
    */

    XStoreName(display, window, "Лаба 2 - Paint XLIB");

    /*
        ==========================================
        СОЗДАЁМ GC
        ==========================================
    */

    gc = XCreateGC(display, window, 0, NULL);

    /*
        Цвет рисования.

        Один цвет по условию лабы.
    */

    XSetForeground(
        display,
        gc,
        BlackPixel(display, screen)
    );

    /*
        Толщина линии
    */

    XSetLineAttributes(
        display,
        gc,

        3,                  // толщина линии

        LineSolid,          // сплошная линия
        CapRound,           // круглые концы
        JoinRound           // круглые соединения
    );

    /*
        ==========================================
        ПОКАЗЫВАЕМ ОКНО
        ==========================================
    */

    XMapWindow(display, window);

    /*
        ==========================================
        ГЛАВНЫЙ ЦИКЛ СОБЫТИЙ
        ==========================================
    */

    while (1) {

        /*
            Ждём следующее событие.
        */

        XNextEvent(display, &event);

        /*
            ==========================================
            СОБЫТИЕ ПЕРЕРИСОВКИ
            ==========================================
        */

        if (event.type == Expose) {

            /*
                Пока ничего не рисуем здесь.

                ВАЖНО:
                Наш рисунок сейчас НЕ сохраняется.

                Если окно перекроется,
                линии могут исчезнуть.

                Для второй лабы это нормально.
            */

            XDrawString(
                display,
                window,
                gc,

                10,
                20,

                "Рисуйте мышью. ESC - выход",

                31
            );
        }

        /*
            ==========================================
            НАЖАТИЕ МЫШИ
            ==========================================
        */

        if (event.type == ButtonPress) {

            /*
                Проверяем:
                нажата ли ЛКМ
            */

            if (event.xbutton.button == Button1) {

                /*
                    Начинаем рисование
                */

                drawing = 1;

                /*
                    Запоминаем стартовую точку
                */

                last_x = event.xbutton.x;
                last_y = event.xbutton.y;

                printf(
                    "Начало рисования: %d %d\n",
                    last_x,
                    last_y
                );
            }
        }

        /*
            ==========================================
            ДВИЖЕНИЕ МЫШИ
            ==========================================
        */

        if (event.type == MotionNotify) {

            /*
                Рисуем,
                только если ЛКМ зажата
            */

            if (drawing) {

                /*
                    Текущая позиция мыши
                */

                int current_x = event.xmotion.x;
                int current_y = event.xmotion.y;

                /*
                    Рисуем линию:
                    от предыдущей точки
                    до текущей
                */

                XDrawLine(

                    display,
                    window,
                    gc,

                    last_x,
                    last_y,

                    current_x,
                    current_y
                );

                /*
                    Обновляем предыдущую точку
                */

                last_x = current_x;
                last_y = current_y;
            }
        }

        /*
            ==========================================
            ОТПУСКАНИЕ МЫШИ
            ==========================================
        */

        if (event.type == ButtonRelease) {

            /*
                Проверяем ЛКМ
            */

            if (event.xbutton.button == Button1) {

                /*
                    Заканчиваем рисование
                */

                drawing = 0;

                printf("Конец рисования\n");
            }
        }

        /*
            ==========================================
            КЛАВИАТУРА
            ==========================================
        */

        if (event.type == KeyPress) {

            KeySym key;

            /*
                Получаем код клавиши
            */

            key = XLookupKeysym(
                &event.xkey,
                0
            );

            /*
                ESC -> выход
            */

            if (key == XK_Escape) {

                printf("Выход...\n");

                break;
            }
        }
    }

    /*
        ==========================================
        ОСВОБОЖДЕНИЕ РЕСУРСОВ
        ==========================================
    */

    XFreeGC(display, gc);

    XDestroyWindow(display, window);

    XCloseDisplay(display);

    return 0;
}
